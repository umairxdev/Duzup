// Release signing is optional and never committed: create keystore.properties (git-ignored) as described in README.md.
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

android {
    namespace = "com.duzup.app"
    compileSdk = 37

    defaultConfig {
        applicationId = "com.duzup.app"
        minSdk = 26
        targetSdk = 36
        versionCode = 1
        versionName = "1.0.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (keystoreProperties.containsKey("storeFile")) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfigs.findByName("release")?.let { signingConfig = it }
        }
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    sourceSets {
        // Exported Room schemas let MigrationTestHelper validate every database version on a device.
        getByName("androidTest").assets.directories.add("$projectDir/schemas")
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    packaging {
        resources.excludes += "/META-INF/{AL2.0,LGPL2.1}"
    }

    testOptions {
        unitTests.isReturnDefaultValues = true
        unitTests.isIncludeAndroidResources = true
        unitTests.all { test ->
            // Robolectric URL-encodes its jar cache path and then cannot find it when the user's home
            // directory contains a space (e.g. "C:\Users\Jane Doe"). Use a space-free cache location there.
            if (System.getProperty("user.home").contains(' ')) {
                val drive = System.getenv("SystemDrive") ?: "C:"
                test.systemProperty("maven.repo.local", "$drive/robolectric-m2")
            }
            test.systemProperty("screenshot.dir", layout.buildDirectory.dir("screenshots").get().asFile.path)
        }
    }

    lint {
        abortOnError = false
        checkReleaseBuilds = false
    }
}

