package com.duzup.app.domain.recurrence

import com.duzup.app.core.model.IntervalUnit
import com.duzup.app.core.model.Recurrence
import com.duzup.app.core.model.RecurrenceRule
import java.time.LocalDate
import java.time.temporal.ChronoUnit

/**
 * Pure recurrence math.
 *
 * Anchor policy: the n-th date is always computed from the ORIGINAL start date
 * (`start + n * interval`), never from the previous occurrence. Month/year arithmetic clamps to the
 * last valid day of the target month, so Jan 31 monthly gives Feb 28/29, then Mar 31 again.
 * A Feb 29 yearly bill falls back to Feb 28 in non-leap years and returns to Feb 29 in leap years.
 */
object RecurrenceCalculator {

    data class Step(val unit: IntervalUnit, val interval: Int)

    const val MAX_DATES = 800

    fun stepOf(recurrence: Recurrence): Step? = when (recurrence.rule) {
        RecurrenceRule.NONE -> null
        RecurrenceRule.DAILY -> Step(IntervalUnit.DAY, 1)
        RecurrenceRule.WEEKLY -> Step(IntervalUnit.WEEK, 1)
        RecurrenceRule.BIWEEKLY -> Step(IntervalUnit.WEEK, 2)
        RecurrenceRule.MONTHLY -> Step(IntervalUnit.MONTH, 1)
        RecurrenceRule.QUARTERLY -> Step(IntervalUnit.MONTH, 3)
        RecurrenceRule.YEARLY -> Step(IntervalUnit.YEAR, 1)
        RecurrenceRule.CUSTOM -> Step(recurrence.unit, recurrence.interval.coerceIn(1, Recurrence.MAX_INTERVAL))
    }

    /** The [index]-th scheduled date (index 0 is [start]). */
    fun dateAt(start: LocalDate, step: Step, index: Int): LocalDate {
        val n = index.toLong() * step.interval
        return when (step.unit) {
            IntervalUnit.DAY -> start.plusDays(n)
            IntervalUnit.WEEK -> start.plusWeeks(n)
            IntervalUnit.MONTH -> start.plusMonths(n)
            IntervalUnit.YEAR -> start.plusYears(n)
        }
    }

    /**
     * All scheduled dates within `[from, to]`, inclusive, never past [endDate] (recurring only).
     * One-time bills yield just [start] when it falls inside the window.
     */
    fun datesBetween(
        start: LocalDate,
        recurrence: Recurrence,
        endDate: LocalDate?,
        from: LocalDate,
        to: LocalDate,
        maxCount: Int = MAX_DATES,
    ): List<LocalDate> {
        val step = stepOf(recurrence)
        if (step == null) return if (start in from..to) listOf(start) else emptyList()

        val last = if (endDate != null && endDate < to) endDate else to
        if (start > last || from > last) return emptyList()

        val result = ArrayList<LocalDate>()
        var index = firstIndexAtOrAfter(start, step, from)
        var guard = 0
        while (guard++ < maxCount * 4 && result.size < maxCount) {
            val date = dateAt(start, step, index)
            if (date > last) break
            if (date >= from) result += date
            index++
        }
        return result
    }

    /** Whether [date] is one of the dates generated by this schedule. */
    fun isScheduled(start: LocalDate, recurrence: Recurrence, date: LocalDate): Boolean {
        val step = stepOf(recurrence) ?: return date == start
        if (date < start) return false
        return when (step.unit) {
            IntervalUnit.DAY -> ChronoUnit.DAYS.between(start, date) % step.interval == 0L
            IntervalUnit.WEEK -> ChronoUnit.DAYS.between(start, date) % (7L * step.interval) == 0L
            IntervalUnit.MONTH -> {
                val months = ChronoUnit.MONTHS.between(start.withDayOfMonth(1), date.withDayOfMonth(1))
                months % step.interval == 0L && dateAt(start, step, (months / step.interval).toInt()) == date
            }
            IntervalUnit.YEAR -> {
                val years = (date.year - start.year).toLong()
                years % step.interval == 0L && dateAt(start, step, (years / step.interval).toInt()) == date
            }
        }
    }

    /** A safe lower bound for the first index whose date is >= [from] (the caller filters the remainder). */
    private fun firstIndexAtOrAfter(start: LocalDate, step: Step, from: LocalDate): Int {
        if (from <= start) return 0
        val raw = when (step.unit) {
            IntervalUnit.DAY -> ChronoUnit.DAYS.between(start, from) / step.interval
            IntervalUnit.WEEK -> ChronoUnit.DAYS.between(start, from) / (7L * step.interval)
            IntervalUnit.MONTH ->
                ChronoUnit.MONTHS.between(start.withDayOfMonth(1), from.withDayOfMonth(1)) / step.interval
            IntervalUnit.YEAR -> (from.year - start.year).toLong() / step.interval
        }
        return (raw - 1).coerceIn(0, Int.MAX_VALUE.toLong()).toInt()
    }
}
